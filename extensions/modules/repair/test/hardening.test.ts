import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { after, before, describe, it } from "node:test";
import { matchMember, readArchiveMember, archiveKind } from "../lib/read-archive.js";
import { checkAutoGenerated } from "../lib/auto-generated.js";
import { applySpecialView } from "../index.js";
import { parsePatch } from "../lib/patch.js";

const dir = mkdtempSync(path.join(tmpdir(), "ceulen-repair-hardening-"));
after(() => rmSync(dir, { recursive: true, force: true }));

// ── A1: member + line ranges ────────────────────────────────────────────────

describe("archive member+range (A1)", () => {
  const proj = path.join(dir, "a1");
  const archive = path.join(proj, "pkg.tgz");
  before(() => {
    mkdirSync(proj, { recursive: true });
    writeFileSync(path.join(proj, "src.ts"), "ignored on disk\n");
    execFileSync("tar", ["-czf", archive, "-C", proj, "src.ts"]);
    // Overwrite the MEMBER content so the disk copy can't mask a failure.
    writeFileSync(path.join(dir, "member-body.txt"), "one\ntwo\nthree\nfour\nfive\n");
    execFileSync("tar", ["-czf", archive, "-C", dir, "member-body.txt"]);
    rmSync(path.join(dir, "member-body.txt"));
  });

  it("pkg.tgz:member:50-80 reads the real member, sliced — not an error", () => {
    const out = applySpecialView("pkg.tgz:member-body.txt:2-3", proj);
    assert.ok(out, "special view triggered");
    assert.match(out!.text, /member-body\.txt/);
    assert.match(out!.text, /two/);
    assert.match(out!.text, /three/);
    assert.doesNotMatch(out!.text, /four|five/);
    assert.doesNotMatch(out!.text, /no member matching/);
  });

  it("member without a range is unchanged", () => {
    const out = applySpecialView("pkg.tgz:member-body.txt", proj);
    assert.ok(out);
    assert.match(out!.text, /one/);
    assert.match(out!.text, /five/);
  });

  it("a bare-number member does NOT peel as a selector", () => {
    // A member literally named "123" parses as a line selector — it must stay
    // whole for the member lookup (no phantom "" member + sliced error text).
    writeFileSync(path.join(dir, "123"), "numeric member\n");
    execFileSync("tar", ["-czf", path.join(proj, "nums.tgz"), "-C", dir, "123"]);
    const out = applySpecialView(`nums.tgz:123`, proj);
    assert.ok(out);
    assert.match(out!.text, /123/);
    assert.match(out!.text, /numeric member/);
    rmSync(path.join(dir, "123"));
  });

  it("tail selector :-2 works over the member body", () => {
    const out = applySpecialView("pkg.tgz:member-body.txt:-2", proj);
    assert.ok(out);
    assert.match(out!.text, /four/);
    assert.match(out!.text, /five/);
    assert.doesNotMatch(out!.text, /one\n|two\n|three\n/);
  });
});

// ── A2: guard × archive-member reads ────────────────────────────────────────

describe("read guard × archive-member reads (A2)", () => {
  it("pkg.tgz:src/x.ts and pkg.tgz:src/x.ts:50-80 pass the guard when the archive exists", async () => {
    const { default: repairModule } = await import("../index.js");
    const proj = await mkdtemp(path.join(tmpdir(), "repair-guard-arch-"));
    const archive = path.join(proj, "pkg.tgz");
    writeFileSync(path.join(proj, "x.ts"), "member\n");
    execFileSync("tar", ["-czf", archive, "-C", proj, "x.ts"]);
    const handlers: Record<string, (event: unknown, ctx: unknown) => unknown> = {};
    const orig = process.env.PI_CODING_AGENT_DIR;
    process.env.PI_CODING_AGENT_DIR = proj;
    try {
      repairModule({
        on: (event: string, handler: (event: unknown, ctx: unknown) => unknown) => { handlers[event] = handler; },
        registerTool: () => {},
        registerCommand: () => {},
      } as never);
      const call = (p: string) =>
        handlers.tool_call!({ toolName: "read", input: { path: p } }, { cwd: proj }) as { block: boolean } | undefined;
      assert.equal(await call("pkg.tgz:x.ts"), undefined, "member read not blocked");
      assert.equal(await call("pkg.tgz:x.ts:1-2"), undefined, "member+range read not blocked");
      assert.equal(await call("pkg.tgz:missing.ts"), undefined, "missing member in an EXISTING archive still passes (the archive view handles it)");
      const blocked = await call("missing.tgz:x.ts") as { block: boolean } | undefined;
      assert.ok(blocked?.block, "a missing .ts-shaped path still blocks");
    } finally {
      if (orig === undefined) delete process.env.PI_CODING_AGENT_DIR;
      else process.env.PI_CODING_AGENT_DIR = orig;
      await rm(proj, { recursive: true, force: true });
    }
  });
});

// ── A4: tar option-injection gate ───────────────────────────────────────────

describe("archive option-injection gate (A4)", () => {
  it("matchMember still matches normal members", () => {
    assert.deepEqual(matchMember(["a.ts", "b.ts"], "a.ts"), { member: "a.ts", via: "exact" });
  });

  it("readArchiveMember refuses a dash-leading member before any spawn", () => {
    // Build an archive with a member named "--checkpoint-action=exec=evil".
    // bsdtar/GNU tar only treats it as an option during EXTRACTION with
    // positional args — exactly what extractMember does — so listing it works.
    const evilDir = path.join(dir, "a4");
    mkdirSync(evilDir, { recursive: true });
    const archive = path.join(evilDir, "evil.tgz");
    const staging = path.join(evilDir, "stage");
    mkdirSync(staging, { recursive: true });
    writeFileSync(path.join(staging, "safe.txt"), "safe\n");
    execFileSync("tar", ["-czf", path.join(evilDir, "plain.tgz"), "-C", staging, "safe.txt"]);
    // Craft the dash member via a tar file listing manipulation: rename inside
    // a ustar header is fiddly — instead create the file and rely on tar -C.
    const evilFile = path.join(staging, "--checkpoint-action=exec=echo pwned");
    writeFileSync(evilFile, "evil\n");
    execFileSync("tar", ["-czf", archive, "-C", staging, "--", "--checkpoint-action=exec=echo pwned", "safe.txt"]);
    const members = ["--checkpoint-action=exec=echo pwned", "safe.txt"];
    assert.equal(archiveKind(archive), "tgz");
    const out = readArchiveMember(archive, "tgz", "--checkpoint-action=exec=echo pwned", "evil.tgz");
    assert.match(out.text, /refusing member/);
    assert.match(out.text, /parsed as tar\/unzip options/);
    void members;
  });

  it("a dash-leading request through the matcher surfaces the gate", () => {
    const out = readArchiveMember(path.join(dir, "a4", "plain.tgz"), "tgz", "--checkpoint-action=exec=echo pwned", "p.tgz");
    assert.match(out.text, /refusing member|no member matching/);
  });
});

// ── A6: auto-gen guard rel path ─────────────────────────────────────────────

describe("auto-generated rel-path correctness (A6)", () => {
  const cwd = path.join(dir, "a6", "proj");
  before(() => mkdirSync(path.join(cwd, "dist"), { recursive: true }));

  it("in-cwd absolute paths still match", () => {
    assert.ok(checkAutoGenerated(path.join(cwd, "package-lock.json"), cwd));
    assert.ok(checkAutoGenerated(path.join(cwd, "dist", "x.js"), cwd));
  });

  it("an absolute path OUTSIDE cwd matches nothing (no garbage rel)", () => {
    const outside = path.resolve(cwd, "../elsewhere/dist/x.js");
    assert.ok(!outside.startsWith(cwd));
    assert.equal(checkAutoGenerated(outside, cwd), null);
  });

  it("cwd itself resolves to '.' and matches nothing", () => {
    assert.equal(checkAutoGenerated(cwd, cwd), null);
  });

  it("relative inputs are matched as given", () => {
    assert.ok(checkAutoGenerated("package-lock.json", cwd));
    assert.equal(checkAutoGenerated("src/app.ts", cwd), null);
  });
});

// ── A9: ascii rename arrow in patch target paths ────────────────────────────

describe("patch rename arrows (A9)", () => {
  it("parsePatch accepts both arrows (lib contract)", () => {
    assert.equal(parsePatch("*** Update File: a.ts → b.ts\n*** End Patch").ops[0]!.movePath, "b.ts");
    assert.equal(parsePatch("*** Update File: a.ts -> b.ts\n*** End Patch").ops[0]!.movePath, "b.ts");
  });

  it("the guard/mtime target parser yields the SOURCE path for both arrows", async () => {
    // parsePatchTargetPaths is module-private; drive it through the wrapper:
    // an auto-gen-guarded RENAME with the ascii arrow must be refused because
    // the SOURCE (a lockfile) is the file being touched.
    const { default: repairModule } = await import("../index.js");
    const proj = await mkdtemp(path.join(tmpdir(), "repair-arrow-"));
    const orig = process.env.PI_CODING_AGENT_DIR;
    process.env.PI_CODING_AGENT_DIR = proj;
    const tools: any[] = [];
    try {
      repairModule({
        on: () => {},
        registerTool: (def: any) => tools.push(def),
        registerCommand: () => {},
      } as never);
      const applyPatch = tools.find((t) => t.name === "apply_patch");
      assert.ok(applyPatch, "apply_patch registered");
      for (const arrow of ["→", "->"]) {
        const res = await applyPatch.execute(
          "t1",
          { patch: `*** Begin Patch\n*** Update File: package-lock.json ${arrow} package-lock2.json\n@@ x\n-y\n+z\n*** End Patch` },
          undefined,
          undefined,
          { cwd: proj },
        );
        assert.equal(res.isError, true, `ascii arrow: rename of a lockfile refused (${arrow})`);
        assert.match(res.content[0].text, /auto-generated/);
      }
    } finally {
      if (orig === undefined) delete process.env.PI_CODING_AGENT_DIR;
      else process.env.PI_CODING_AGENT_DIR = orig;
      await rm(proj, { recursive: true, force: true });
    }
  });
});
